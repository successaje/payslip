// Turns drizzle/*.sql into src/lib/db/migrations.ts so the app can create its
// own schema on first use (the hosted database is provisioned empty and its
// credentials are not exportable from Vercel). Every statement is made
// idempotent, so running it on each cold start is safe and cheap.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
const files = readdirSync("drizzle").filter((f) => f.endsWith(".sql")).sort();
const statements = [];
for (const f of files) {
  for (const raw of readFileSync(`drizzle/${f}`, "utf8").split("--> statement-breakpoint")) {
    const s = raw.trim().replace(/;$/, "");
    if (!s) continue;
    statements.push(
      s
        .replace(/^CREATE TABLE `/, "CREATE TABLE IF NOT EXISTS `")
        .replace(/^CREATE UNIQUE INDEX `/, "CREATE UNIQUE INDEX IF NOT EXISTS `")
        .replace(/^CREATE INDEX `/, "CREATE INDEX IF NOT EXISTS `"),
    );
  }
}
const out = `// Generated by scripts/embed-migrations.mjs from drizzle/*.sql. Do not edit.\nexport const statements: string[] = ${JSON.stringify(statements, null, 2)};\n`;
writeFileSync("src/lib/db/migrations.ts", out);
console.log(`${statements.length} statements from ${files.length} file(s)`);
